"""看门狗的配置。"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class WatchdogConfig:
    """看门狗：盯着客户端进程在不在，掉了就拉起来。

    🔴 **默认关**：它会真起进程。发进程类的东西默认开着，等于让人在不知情的情况下
    多了一个会自己弹窗口的常驻动作。

    🔴 **它只保证进程活着，绝不填密码。** 交易登录那道门仍然只由 `/v1/session/ensure`
    触发。理由是硬的：密码额度是每天一次，而看门狗每分钟醒一次——让它去登录，
    第一次失败就把当天额度烧光，且是在没人看着的时候烧的。

    🔴 **只拉起，绝不 kill。** 进程还活着但没响应时把它杀掉重启，会打断正在飞的委托。
    "没响应"和"没进程"是两件事，看门狗只处理后者。
    """

    #: 默认关（见类 docstring 第一条）。
    enabled: bool = False
    #: 醒一次的间隔。默认 60 秒：进程枚举是零成本的，但拉起进程后客户端要几秒才到位，
    #: 太密的话会在同一次故障里连着拉好几次。
    interval_seconds: int = 60
    #: 工作时段（本地时间，闭区间）。默认覆盖开盘前到收盘后一点：
    #: 09:00 之前要给 09:00 那条登录任务把进程准备好，15:10 之后当天不再报单。
    window_start: str = "08:40"
    window_end: str = "15:10"
    #: 只在周一到周五工作。
    #: ⚠️ **刻意不判节假日**：本服务不碰数据库、不该有交易日历这个依赖。
    #: 节假日多起一次客户端的代价是桌面上多一个窗口；引一份日历进来的代价是给这个
    #: 只该说 HTTP 的服务加一个它不该有的数据依赖。
    weekdays_only: bool = True
    #: 每个进程每天最多拉起几次。防的是"起来就自己退"的死循环——
    #: 那种情况下无限重启只会刷屏，而真正要做的是让人来看一眼。
    max_starts_per_day: int = 3
